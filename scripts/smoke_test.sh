#!/usr/bin/env bash
#
# Live smoke test of the OAR base system: builds the workspace, then starts the
# three real daemons (server, client, compute nodes) as separate processes and
# drives them with the real `oarsub` / `oarstat` binaries.
#
#   scripts/smoke_test.sh [--no-build] [--keep]
#
#   --no-build  reuse the existing `target/debug` binaries
#   --keep      leave the temporary directory and the daemons running
#
# Everything is created under a temporary directory:
#
#   client.sock   unix domain socket of the client daemon (JSON protocol)
#   oar.conf      generated configuration, read through OAR_CONFIG
#   logs/         one log file per daemon
#
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BIN="$ROOT/target/debug"
BUILD=1
KEEP=0

for arg in "$@"; do
    case "$arg" in
        --no-build) BUILD=0 ;;
        --keep) KEEP=1 ;;
        -h|--help) sed -n '2,16p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *) echo "unknown option: $arg" >&2; exit 2 ;;
    esac
done

log() { printf '\n\033[1;34m==>\033[0m %s\n' "$*"; }
fail() { printf '\n\033[1;31mFAILED:\033[0m %s\n' "$*" >&2; exit 1; }
ok() { printf '\033[1;32m ok \033[0m %s\n' "$*"; }

# --- workspace --------------------------------------------------------------

if [ "$BUILD" = 1 ]; then
    log "building the workspace"
    cargo build --workspace --manifest-path "$ROOT/Cargo.toml"
fi
for name in oar-server oar-client oar-node oarsub oarstat; do
    [ -x "$BIN/$name" ] || fail "missing binary $BIN/$name (run without --no-build)"
done

WORK="$(mktemp -d "${TMPDIR:-/tmp}/oar-smoke.XXXXXX")"
mkdir -p "$WORK/logs"
PIDS=()

cleanup() {
    status=$?
    if [ "$KEEP" = 1 ]; then
        echo "kept the run directory: $WORK"
        return
    fi
    for pid in "${PIDS[@]:-}"; do
        kill "$pid" 2>/dev/null || true
    done
    for pid in "${PIDS[@]:-}"; do
        wait "$pid" 2>/dev/null || true
    done
    if [ "$status" -ne 0 ]; then
        echo "--- daemon logs ---" >&2
        tail -n 40 "$WORK"/logs/*.log >&2 || true
    fi
    rm -rf "$WORK"
}
trap cleanup EXIT

CLIENT_SOCKET="$WORK/client.sock"
CONF="$WORK/oar.conf"
PORT=6700

# The configuration is plain OAR3 `KEY=VALUE` (dotenv) syntax.
cat > "$CONF" <<EOF
# generated by scripts/smoke_test.sh
SERVER_HOSTNAME="127.0.0.1"
SERVER_PORT="$PORT"
CLIENT_SOCKET="$CLIENT_SOCKET"
OARSUB_DEFAULT_RESOURCES="/resource_id=1,walltime=1:00:00"
AUTOMATON_WAIT="1"
SCHEDULER_TIMEOUT="1"
FINAUD_FREQUENCY="2"
NODE_HEARTBEAT="2"
SIMULATED_JOB_DURATION="2"
LOG_LEVEL="3"
EOF

export OAR_CONFIG="$CONF"

start() { # start <name> <binary>
    local name="$1"; shift
    "$@" >"$WORK/logs/$name.log" 2>&1 &
    local pid=$!
    PIDS+=("$pid")
    echo "  $name: pid $pid (log: logs/$name.log)"
}

wait_for() { # wait_for <description> <command...>
    local what="$1"; shift
    local deadline=$((SECONDS + 20))
    while ! "$@" >/dev/null 2>&1; do
        if [ "$SECONDS" -ge "$deadline" ]; then
            fail "timed out waiting for $what"
        fi
        sleep 0.2
    done
}

port_open() { # port_open <host> <port>
    bash -c "exec 3<>/dev/tcp/$1/$2" 2>/dev/null
}

# --- daemons ----------------------------------------------------------------

log "starting the server (TCP gRPC)"
start oar-server "$BIN/oar-server"
wait_for "the server port" port_open 127.0.0.1 "$PORT"
ok "server listening on 127.0.0.1:$PORT"

log "starting the client daemon"
start oar-client "$BIN/oar-client"
wait_for "the client socket" test -S "$CLIENT_SOCKET"
ok "client daemon listening on $CLIENT_SOCKET"

log "starting two compute nodes"
OAR_NODE_ID=node-1 OAR_NODE_ADDRESS=127.0.0.1:7001 start oar-node-1 "$BIN/oar-node"
OAR_NODE_ID=node-2 OAR_NODE_ADDRESS=127.0.0.1:7002 start oar-node-2 "$BIN/oar-node"
wait_for "the first node" port_open 127.0.0.1 7001
wait_for "the second node" port_open 127.0.0.1 7002
ok "both nodes are up"

# --- user commands ----------------------------------------------------------

log "oarsub: three jobs"
"$BIN/oarsub" -l nodes=1,walltime=1:00 -- "echo hello from smoke test"
"$BIN/oarsub" -l nodes=2 "exit=0"
"$BIN/oarsub" -l nodes=1 "exit=3"
ok "three jobs submitted"

log "oarstat: the whole list"
STAT="$("$BIN/oarstat")"
echo "$STAT"
[ "$(grep -c '^[0-9]' <<<"$STAT")" -eq 3 ] || fail "expected 3 jobs in oarstat"
ok "three jobs listed"

log "oarstat: a single job"
"$BIN/oarstat" -j 1 | tee "$WORK/oarstat-1.txt"
grep -q '^1 ' "$WORK/oarstat-1.txt" || fail "oarstat -j 1 did not report job 1"
ok "single job status works"

log "waiting for the jobs to be executed and terminated"
wait_for "all jobs terminated" bash -c \
    "'$BIN/oarstat' | grep -c 'Terminated' | grep -qx 3"
"$BIN/oarstat"
ok "all jobs terminated"

log "checking the reported exit codes"
wait_for "job 3 exit code" bash -c "'$BIN/oarstat' -j 3 | grep -q ' 3\$'"
"$BIN/oarstat" -j 1 | grep -q ' 0$' || fail "job 1 should have exit code 0"
"$BIN/oarstat" -j 2 | grep -q ' 0$' || fail "job 2 should have exit code 0"
"$BIN/oarstat" -j 3 | grep -q ' 3$' || fail "job 3 should have exit code 3"
ok "exit codes are reported"

log "errors are reported, not ignored"
if "$BIN/oarsub" -l nodes 2>/dev/null; then
    fail "a malformed resource request must fail"
fi
if "$BIN/oarstat" -j 999 2>/dev/null; then
    fail "an unknown job must fail"
fi
if "$BIN/oarstat" -s flying 2>/dev/null; then
    fail "an unknown state must fail"
fi
ok "invalid inputs are refused"

log "the server and the nodes are still healthy"
"$BIN/oarstat" >/dev/null || fail "oarstat stopped working"
grep -qi "terminated" "$WORK/logs/oar-server.log" 2>/dev/null ||
    echo "  (no 'terminated' line in the server log, tracing level may be too low)"
ok "smoke test passed"
